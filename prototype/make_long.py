"""
One command from a long story to a scheduled 16:9 video (~8-10 min).

  python prototype/make_long.py prototype/long_stanford              # voice -> build -> stills -> export -> thumbnail
  python prototype/make_long.py prototype/long_stanford --upload     # ...then upload into the next Sunday 18:00 IST slot
  python prototype/make_long.py prototype/long_stanford --estimate   # no TTS: provisional timings (look-check only)
  python prototype/make_long.py prototype/long_stanford --stills     # stop after the contact sheet

A long folder needs only story.json (see prototype/STORY_GUIDE_LONG.md): {"youtube": {...}, "thumbnail": {...}, "scenes": [...]}.
"""
import os, sys, json, re, glob, shutil, subprocess, datetime as dt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(__file__))
SKILL = os.environ.get("ANIMATE_SKILL", os.path.join(ROOT, "tools", "animate"))
BUILD = ["../sketch_kit/head_wide.html", "src/timing.js", "../sketch_kit/timeline.js", "kit/core.js", "style",
         "../sketch_kit/people.js", "../sketch_kit/long.js", "src/scenes.js", "../sketch_kit/bridges_wide.js", "kit/morph.js",
         "kit/board.js", "kit/score-head.js", "../sketch_kit/score.js", "kit/score-tail.js"]
SLOT_UTC = dt.time(12, 30)      # Sunday 18:00 IST


def run(cmd, **kw):
    print("  $", " ".join(str(c) for c in cmd)[:140], flush=True)
    r = subprocess.run(cmd, capture_output=True, encoding="utf-8", errors="replace", **kw)
    if r.returncode != 0:
        print(r.stdout[-2500:], r.stderr[-2500:]); sys.exit(f"step failed: {cmd[0]} {cmd[1] if len(cmd) > 1 else ''}")
    return r.stdout


def scaffold(piece, story):
    pj = os.path.join(piece, "piece.json")
    meta = json.load(open(pj)) if os.path.exists(pj) else {
        "name": os.path.basename(piece), "title": story.get("title", ""),
        "format": {"width": 1920, "height": 1080, "fps": 24, "bpm": 120, "duration": 480.0, "frames": 11520},
        "storyFormat": "voice-led long story (data-driven scenes)", "style": "sketchbook",
        "voice": {"file": "voice/voice.wav", "music": -26, "gain": 0},
        "review": {"safe": {"top": 60, "bottom": 110, "right": 60}, "refs": {}}}
    meta["build"] = BUILD
    meta.pop("scenes", None)
    json.dump(meta, open(pj, "w"), indent=2)
    os.makedirs(os.path.join(piece, "src"), exist_ok=True)
    js = ("// generated by make_long.py from story.json — do not edit\n"
          f"const LONG = {json.dumps(story, ensure_ascii=False)};\n"
          "const SCENES = LONG.scenes.map((sc, i) => () => drawLongScene(sc, i));\n")
    open(os.path.join(piece, "src", "scenes.js"), "w", encoding="utf-8").write(js)


def estimate(piece, story):
    from make_voice import write_timing_js
    words, starts, t = [], [], 0.0
    for sc in story["scenes"]:
        starts.append(round(t, 3))
        for w in sc["say"].split():
            d = max(0.18, len(re.sub(r"[^A-Za-z0-9]", "", w)) * 0.065)
            words.append({"text": w, "start": round(t, 2), "end": round(t + d, 2)}); t += d + (0.25 if w[-1:] in ".,?!:" else 0.05)
    json.dump({"S": starts + [round(t, 3)], "words": words, "estimated": True}, open(os.path.join(piece, "timing.json"), "w"), indent=1)
    write_timing_js(piece, starts, t, words)
    print(f"  estimated timing: {t / 60:.1f} min")


def chapters(story, S):
    """YouTube chapter lines from the scenes' "tag"s (first must be 0:00, at least 3, >= 10 s apart)."""
    pts = [(0.0, "Intro")]
    for i, sc in enumerate(story["scenes"]):
        if sc.get("tag") and S[i] - pts[-1][0] >= 12:
            pts.append((S[i], sc["tag"][:1].upper() + sc["tag"][1:]))
    if len(pts) < 3: return ""
    f = lambda t: f"{int(t // 60)}:{int(t % 60):02d}"
    return "Chapters:\n" + "\n".join(f"{f(t)} {name}" for t, name in pts)


def thumbnail(piece, story, S):
    """A 1280x720 thumbnail: a frame from the video plus big hand-lettered text."""
    from PIL import Image, ImageDraw, ImageFont
    th = story.get("thumbnail", {}); i = min(th.get("scene", 1), len(S) - 2)
    t = S[i] + (S[i + 1] - S[i]) * 0.85
    raw = os.path.join(piece, "thumb_raw.png")
    run(["node", os.path.join(SKILL, "tools", "still.mjs"), piece, f"{t:.2f}", raw])
    im = Image.open(raw).convert("RGB"); w0, h0 = im.size
    cw = int(h0 * 0.86 * 16 / 9); x0 = (w0 - cw) // 2          # drop the caption strip, keep 16:9
    im = im.crop((x0, 0, x0 + cw, int(h0 * 0.86))).resize((1280, 720))
    d = ImageDraw.Draw(im)
    font = None
    for p in ("C:/Windows/Fonts/Inkfree.ttf", "C:/Windows/Fonts/segoeprb.ttf", "C:/Windows/Fonts/arialbd.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"):
        if os.path.exists(p):
            font = p; break
    text = th.get("text", story.get("title", "")).upper()
    words = text.split(); lines, cur = [], ""
    for w in words:
        if cur and len(cur + " " + w) > 13: lines.append(cur); cur = w
        else: cur = (cur + " " + w).strip()
    lines.append(cur)
    size = 104 if len(lines) <= 2 else 86
    f = ImageFont.truetype(font, size) if font else ImageFont.load_default()
    y = 36
    for ln in lines:
        d.text((52, y), ln, font=f, fill="#fffdf6", stroke_width=10, stroke_fill="#14110f")
        d.text((52, y), ln, font=f, fill="#e4572e" if ln is lines[-1] else "#fffdf6", stroke_width=0)
        y += int(size * 1.05)
    out = os.path.join(piece, "thumbnail.jpg")
    im.save(out, quality=92)
    os.remove(raw)
    return out


def teaser(piece, story, S, max_s=75):
    """A vertical Instagram Reel (<= 90 s API limit): the opening of the long video on a paper background, with the title on top and
    'full story on YouTube' below. Cuts at a scene boundary so it ends on a complete beat."""
    from PIL import Image, ImageDraw, ImageFont
    cuts = [t for t in S[1:-1] if 35 <= t <= max_s] or [min(60.0, S[-1])]
    T = cuts[-1]
    font = next((p for p in ("C:/Windows/Fonts/Inkfree.ttf", "C:/Windows/Fonts/segoeprb.ttf", "C:/Windows/Fonts/arialbd.ttf",
                             "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf") if os.path.exists(p)), None)
    F = lambda n: ImageFont.truetype(font, n) if font else ImageFont.load_default()
    im = Image.new("RGBA", (1080, 1920), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    def block(text, y, size, fill):
        words, lines, cur = text.split(), [], ""
        for w in words:
            if cur and len(cur + " " + w) > 30: lines.append(cur); cur = w
            else: cur = (cur + " " + w).strip()
        lines.append(cur)
        for ln in lines:
            w = d.textlength(ln, font=F(size)); d.text(((1080 - w) / 2, y), ln, font=F(size), fill=fill); y += int(size * 1.15)
        return y
    block(story.get("title", ""), 190, 84, "#1b1a17")
    y = block("THE FULL STORY IS ON YOUTUBE", 1380, 58, "#e4572e")
    block("Link in bio. Search MindShift Productivity.", y + 30, 44, "#5b5448")
    banner = os.path.join(piece, "teaser_banner.png"); im.save(banner)
    out = os.path.join(ROOT, "prototype", f"LONGTEASER_{os.path.basename(piece)}.mp4")
    vf = (f"[0:v]scale=1080:-2[v];color=c=0xf2ead8:s=1080x1920:d={T:.2f}[bg];[bg][v]overlay=0:656[b];[b][1:v]overlay=0:0,format=yuv420p[o]")
    run(["ffmpeg", "-v", "error", "-y", "-t", f"{T:.2f}", "-i", os.path.join(piece, "renders", "share.mp4"), "-loop", "1", "-i", banner,
         "-filter_complex", vf, "-map", "[o]", "-map", "0:a", "-af", f"afade=t=out:st={T - 0.6:.2f}:d=0.6", "-r", "30",
         "-c:v", "libx264", "-crf", "20", "-c:a", "aac", "-b:a", "160k", "-shortest", out])
    os.remove(banner)
    return out


def next_slot():
    taken = []
    for f in glob.glob(os.path.join(ROOT, "prototype", "long_*", "upload.json")):
        p = json.load(open(f)).get("publish_at")
        if p: taken.append(dt.datetime.fromisoformat(p.replace("Z", "+00:00")))
    after = max([dt.datetime.now(dt.timezone.utc) + dt.timedelta(hours=2)] + taken)
    d = after.date()
    while True:
        cand = dt.datetime.combine(d, SLOT_UTC, tzinfo=dt.timezone.utc)
        if d.weekday() == 6 and cand > after:
            return cand.strftime("%Y-%m-%dT%H:%M:%SZ")
        d += dt.timedelta(days=1)


def main(piece, flags):
    piece = os.path.abspath(piece)
    story = json.load(open(os.path.join(piece, "story.json"), encoding="utf-8"))
    scaffold(piece, story)
    tj = os.path.join(piece, "src", "timing.js")
    if "--estimate" in flags:
        estimate(piece, story)
    else:
        jt = os.path.join(piece, "timing.json")
        if os.path.exists(jt) and json.load(open(jt)).get("estimated"):
            os.remove(jt); os.remove(tj)
        if not os.path.exists(tj):
            run([sys.executable, "-u", os.path.join(ROOT, "prototype", "make_voice_long.py"), piece])
    node = lambda tool, *a: run(["node", os.path.join(SKILL, "tools", tool), piece, *a])
    node("build.mjs")
    S = json.load(open(os.path.join(piece, "timing.json")))["S"]
    print(f"  {len(S) - 1} scenes, {S[-1] / 60:.1f} min")
    mids = ",".join(f"{(a + b) / 2:.2f}" for a, b in zip(S[:-1], S[1:]))
    node("still.mjs", mids, os.path.join(piece, "look.png"), "--scale", "0.2")
    if "--stills" in flags: return
    node("export.mjs", "--share")
    review = node("review.mjs")
    text = [l for l in review.splitlines() if l.startswith("text:")]
    print("  " + (text[0] if text else "text: (no verdict)"))
    out = os.path.join(ROOT, "prototype", f"LONG_{os.path.basename(piece)}.mp4")
    shutil.copy(os.path.join(piece, "renders", "share.mp4"), out)
    thumb = thumbnail(piece, story, S)
    tz = teaser(piece, story, S)
    print(f"  video: {out}\n  thumbnail: {thumb}\n  Instagram teaser: {tz}")
    if "--upload" in flags:
        if os.path.exists(os.path.join(piece, "upload.json")):
            sys.exit("already uploaded (upload.json exists)")
        slot = next_slot()
        print(f"  uploading, scheduled for {slot}")
        print(run([sys.executable, os.path.join(ROOT, "prototype", "upload_long.py"), piece, slot, chapters(story, S)], cwd=ROOT))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
